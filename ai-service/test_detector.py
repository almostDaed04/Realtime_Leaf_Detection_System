"""
Leaf Detector Test Script
Usage:
    python test_detector.py <path_to_image>
"""

import sys
import os
from pathlib import Path
from PIL import Image
from ultralytics import YOLO

# Add ai-service to path
AI_SERVICE_DIR = Path(__file__).parent.resolve()
sys.path.insert(0, str(AI_SERVICE_DIR))

from services.detector import LeafDetector


def run_test(image_path: str):
    path = Path(image_path)
    if not path.exists():
        print(f"❌ Error: File not found: {image_path}")
        return

    print("=" * 60)
    print(f"📸 Testing Image: {path.name}")
    print("=" * 60)

    try:
        img = Image.open(path)
        print(f"• Image Dimensions : {img.width} x {img.height} (width x height)")
    except Exception as e:
        print(f"❌ Could not open image: {e}")
        return

    # 1. Initialize detector
    detector = LeafDetector()

    print(f"• Weights Path     : {detector.model.ckpt_path}")
    print(f"• Total Classes    : {len(detector.model.names)}")
    print(f"• Is Custom Model  : {detector._is_custom_model}")

    if not detector._is_custom_model:
        print("  ⚠️ Notice: This is the default 80-class COCO model, NOT a trained leaf detector!")

    # 2. Raw YOLO inference
    model_name = Path(detector.model.ckpt_path).name if hasattr(detector.model, "ckpt_path") and detector.model.ckpt_path else "YOLO"
    print(f"\n--- Raw YOLO Predictions ({model_name}) ---")
    raw_results = detector.model(path, conf=0.15, verbose=False)
    raw_boxes = raw_results[0].boxes if raw_results else []

    if len(raw_boxes) == 0:
        print(f"  (No objects detected by {model_name} at conf >= 0.15)")
    else:
        for i, box in enumerate(raw_boxes):
            cls_id = int(box.cls[0].item())
            cls_name = detector.model.names.get(cls_id, str(cls_id))
            conf = float(box.conf[0].item())
            xyxy = [round(c, 1) for c in box.xyxy[0].tolist()]
            print(f"  [{i + 1}] Class: {cls_name} (id {cls_id}) | Conf: {conf:.2%} | Box: {xyxy}")

    # 3. LeafDetector Service Output
    print("\n--- LeafDetector Service Result ---")
    with open(path, "rb") as f:
        result = detector.detect(f.read())

    print(f"• Leaf Count : {result['leaf_count']}")
    print(f"• Boxes      : {result['boxes']}")

    if not detector._is_custom_model and result['leaf_count'] == 1:
        # Check if it was fallback
        b = result['boxes'][0]
        if b == [round(img.width * 0.05, 2), round(img.height * 0.05, 2), round(img.width * 0.95, 2), round(img.height * 0.95, 2)]:
            print("\n  👉 Result Explanation: This 1 box was generated by the FALLBACK mechanism")
            print("     because the COCO model found 0 leaves. It assumed the whole image is 1 leaf.")

    print("=" * 60)


if __name__ == "__main__":
    if len(sys.argv) > 1:
        img_arg = sys.argv[1]
    else:
        # Default test image if none provided
        sample = AI_SERVICE_DIR / "merged_dataset" / "test" / "Mango" / "20211008_125104 (Custom).jpg"
        img_arg = str(sample)
        print(f"No image path specified. Using default sample: {sample.name}\n")

    run_test(img_arg)
